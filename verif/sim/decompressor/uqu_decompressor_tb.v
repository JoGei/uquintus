`default_nettype none
`include "uqu_config.vh"
// Verification-only expansion/strategy controls and DE integration, no storage.
module uqu_decompressor_tb #(
    parameter ISA_C = 0,
    parameter MUA_C_IMPL = `UQU_C_IMPL_DECOMPRESS,
    parameter MUA_C_DECOMPRESS_STAGE = `UQU_C_DECOMPRESS_IF,
    parameter ISA_E = 0,
    parameter ISA_M = 0,
    parameter ISA_ZFINX = 0
) (
    input wire [31:0] instr_i,
    output wire [31:0] instr_o,
    output wire [31:0] original_instr_o,
    output wire  compressed_o,
    output wire  illegal_o,
    output wire  hint_o,
    input wire [31:0] pc_i,
    input wire [31:0] rs0_i,
    input wire [31:0] rs1_i,
    input wire  ready_i,
    input wire  permit_i,
    output wire  dec_native_o,
    output wire  dec_illegal_o,
    output wire  dec_illegal_reg_o,
    output wire [2:0] dec_rs_used_o,
    output wire [4:0] dec_rs1_o,
    output wire [4:0] dec_rs2_o,
    output wire [4:0] dec_rs3_o,
    output wire  dec_rd_we_o,
    output wire [4:0] dec_rd_o,
    output wire [31:0] dec_imm_o,
    output wire [1:0] dec_fu_o,
    output wire [4:0] dec_op_o,
    output wire [1:0] dec_a_sel_o,
    output wire [1:0] dec_b_sel_o,
    output wire  dec_pass_link_o,
    output wire [1:0] dec_branch_o,
    output wire [2:0] dec_branch_op_o,
    output wire  dec_lsu_o,
    output wire  dec_mem_we_o,
    output wire [2:0] dec_mem_op_o,
    output wire [2:0] dec_wb_kind_o,
    output wire [2:0] dec_system_o,
    output wire  dec_serialize_o,
    output wire [11:0] dec_csr_addr_o,
    output wire [2:0] dec_csr_op_o,
    output wire  dec_csr_imm_o,
    output wire [2:0] dec_rm_o,
    output wire  de_valid_o,
    output wire  de_branch_resolve_o,
    output wire  de_branch_taken_o,
    output wire  de_exception_valid_o,
    output wire [31:0] de_next_pc_o,
    output wire [31:0] de_pass_data_o,
    output wire [31:0] de_exception_tval_o,
    output wire [4:0] de_exception_cause_o
);
    localparam EXPAND_IF = (MUA_C_IMPL == `UQU_C_IMPL_DECOMPRESS) &&
                          (MUA_C_DECOMPRESS_STAGE == `UQU_C_DECOMPRESS_IF);
    uqu_decompressor #(.ISA_C(ISA_C)) u_decompressor (
        .instr_i(instr_i), .instr_o(instr_o), .original_instr_o(original_instr_o),
        .compressed_o(compressed_o), .illegal_o(illegal_o), .hint_o(hint_o)
    );
    uqu_decoder_select #(
        .ISA_C(ISA_C), .ISA_E(ISA_E), .ISA_M(ISA_M), .ISA_ZFINX(ISA_ZFINX),
        .MUA_C_IMPL(MUA_C_IMPL), .MUA_C_DECOMPRESS_STAGE(MUA_C_DECOMPRESS_STAGE)
    ) u_decoder_select (
        .instr_i(EXPAND_IF ? instr_o : instr_i),
        .original_instr_i(original_instr_o), .compressed_i(compressed_o),
        .xif_force_i(1'b0), .illegal_c_o(),
        .native_o(dec_native_o),
        .illegal_o(dec_illegal_o),
        .illegal_reg_o(dec_illegal_reg_o),
        .rs_used_o(dec_rs_used_o),
        .rs1_o(dec_rs1_o),
        .rs2_o(dec_rs2_o),
        .rs3_o(dec_rs3_o),
        .rd_we_o(dec_rd_we_o),
        .rd_o(dec_rd_o),
        .imm_o(dec_imm_o),
        .fu_o(dec_fu_o),
        .op_o(dec_op_o),
        .a_sel_o(dec_a_sel_o),
        .b_sel_o(dec_b_sel_o),
        .pass_link_o(dec_pass_link_o),
        .branch_o(dec_branch_o),
        .branch_op_o(dec_branch_op_o),
        .lsu_o(dec_lsu_o),
        .mem_we_o(dec_mem_we_o),
        .mem_op_o(dec_mem_op_o),
        .wb_kind_o(dec_wb_kind_o),
        .system_o(dec_system_o),
        .serialize_o(dec_serialize_o),
        .csr_addr_o(dec_csr_addr_o),
        .csr_op_o(dec_csr_op_o),
        .csr_imm_o(dec_csr_imm_o),
        .rm_o(dec_rm_o)
    );
    uqu_stage_de #(
        .ISA_C(ISA_C),
        .MUA_C_IMPL(MUA_C_IMPL),
        .MUA_C_DECOMPRESS_STAGE(MUA_C_DECOMPRESS_STAGE),
        .ISA_E(ISA_E),
        .ISA_M(ISA_M),
        .ISA_ZFINX(ISA_ZFINX)
    ) u_de (
        .clk_i(1'b0),
        .rst_ni(1'b1),
        .flush_i(1'd0),
        .valid_i(1'b1),
        .ready_o(),
        .valid_o(de_valid_o),
        .ready_i(ready_i),
        .permit_i(permit_i),
        .pc_i(pc_i),
        .instr_i(EXPAND_IF ? instr_o : instr_i),
        .original_instr_i(original_instr_o),
        .compressed_i(compressed_o),
        .priv_m_i(1'b1),
        .debug_mode_i(1'd0),
        .tw_i(1'd0),
        .frm_i(3'd0),
        .exception_valid_i(EXPAND_IF && illegal_o),
        .exception_cause_i(5'd2),
        .exception_tval_i(original_instr_o),
        .rs0_i(rs0_i),
        .rs1_i(rs1_i),
        .rs2_i(32'd0),
        .rs_ready_i(3'b111),
        .rs_ex_guaranteed_i(3'd0),
        .rs0_addr_o(),
        .rs1_addr_o(),
        .rs2_addr_o(),
        .rs_used_o(),
        .rs_need_now_o(),
        .rs_ex_used_o(),
        .rs_captured_o(),
        .native_o(), .late_c_o(),
        .fu_o(),
        .op_o(),
        .a_sel_o(),
        .b_sel_o(),
        .imm_o(),
        .a_o(),
        .b_o(),
        .c_o(),
        .rm_o(),
        .pass_data_o(de_pass_data_o),
        .store_data_o(),
        .rd_we_o(),
        .rd_o(),
        .rd1_o(),
        .rd_pending_o(),
        .lsu_o(),
        .mem_we_o(),
        .mem_op_o(),
        .wb_kind_o(),
        .system_o(),
        .serialize_o(),
        .csr_addr_o(),
        .csr_op_o(),
        .csr_src_o(),
        .csr_src_zero_o(),
        .control_flow_o(),
        .branch_resolve_o(de_branch_resolve_o),
        .branch_taken_o(de_branch_taken_o),
        .branch_target_o(),
        .next_pc_o(de_next_pc_o),
        .exception_valid_o(de_exception_valid_o),
        .exception_cause_o(de_exception_cause_o),
        .exception_tval_o(de_exception_tval_o),
        .xif_force_i(1'd0),
        .xif_id_valid_i(1'd0),
        .xif_id_i(3'd0),
        .hart_id_i(32'd0),
        .xif_issued_o(),
        .xif_accepted_o(),
        .xif_cleanup_valid_o(),
        .xif_cleanup_id_o(),
        .xif_cleanup_ready_i(1'd0),
        .xif_issue_valid_o(),
        .xif_issue_ready_i(1'd0),
        .xif_issue_instr_o(),
        .xif_issue_hartid_o(),
        .xif_issue_id_o(),
        .xif_issue_accept_i(1'd0),
        .xif_issue_writeback_i(1'd0),
        .xif_issue_register_read_i(3'd0),
        .xif_register_valid_o(),
        .xif_register_ready_i(1'd0),
        .xif_register_hartid_o(),
        .xif_register_id_o(),
        .xif_register_rs_o(),
        .xif_register_rs_valid_o()
    );
endmodule
`default_nettype wire
