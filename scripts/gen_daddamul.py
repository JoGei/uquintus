#!/usr/bin/env python3
"""Generate the fixed-RV32 combinational structural Dadda multiplier.

The checked-in Verilog is a build input; generation is not a synthesis dependency.
Use --check to detect stale output. Carries are packed at their actual weights.
"""
from collections import deque
from dataclasses import dataclass
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'src/uquintus/uqu_daddamul.v'


@dataclass
class Counter:
    inputs: tuple
    sum: str
    carry: str
    column: int


@dataclass
class Stage:
    target: int
    input_heights: list
    output_columns: list
    counters: list

    @property
    def output_heights(self):
        return list(map(len, self.output_columns))


def initial_columns(width):
    columns = [[] for _ in range(2*width)]
    for i in range(width):
        for j in range(width):
            columns[i+j].append(f'pp[{width*i+j}]')
    columns[width-1] += ['signed_a', 'signed_b']
    columns[2*width-1].append('(signed_a | signed_b)')
    return columns


def targets_for(height):
    limits = [2]
    while limits[-1] < height:
        limits.append(3*limits[-1]//2)
    return list(reversed(limits[:-1]))


def stages_for(width=32):
    heights = list(map(len, initial_columns(width)))
    stages = []
    for target in targets_for(max(heights)):
        outputs = [[] for _ in heights]
        counters = []
        full = half = 0
        for col, height in enumerate(heights):
            old = deque(f'heap_i[{row*len(heights)+col}]' for row in range(height))
            # Outputs from this pass are never counter inputs in this pass.
            # Include incoming carry dots in output height when selecting FAs/HAs.
            while len(old)+len(outputs[col]) > target:
                excess = len(old)+len(outputs[col])-target
                count = 3 if excess >= 2 else 2
                assert len(old) >= count, 'invalid non-ripple Dadda schedule'
                name, index = ('fa', full) if count == 3 else ('ha', half)
                full += int(count == 3)
                half += int(count == 2)
                counter = Counter(tuple(old.popleft() for _ in range(count)),
                                  f'{name}_sum[{index}]', f'{name}_carry[{index}]', col)
                counters.append(counter)
                outputs[col].append(counter.sum)
                if col+1 < len(heights):
                    outputs[col+1].append(counter.carry)
            outputs[col].extend(old)
        assert max(map(len, outputs)) <= target
        stages.append(Stage(target, heights, outputs, counters))
        heights = stages[-1].output_heights
    return stages


def packed_assignments(port, columns, rows):
    lines = []
    for row in range(rows):
        bits = [column[row] if row < len(column) else "1'b0" for column in reversed(columns)]
        lines.append(f'    assign {port}[{64*row} +: 64] = {{')
        for offset in range(0, 64, 8):
            lines.append('        '+', '.join(bits[offset:offset+8])+(',' if offset+8 < 64 else ''))
        lines.append('    };')
    return lines


def generate():
    stages = stages_for()
    lines = ['// SPDX-License-Identifier: Unlicense',
             '// Generated by scripts/gen_daddamul.py; edit the generator, not this file.',
             '// Combinational 32x32 Dadda tree with integrated signed corrections.',
             '// Signed controls select interpretation, not the operand sign bits.',
             '`default_nettype none', '', 'module uqu_daddamul (',
             '    input  wire [31:0] a_i,', '    input  wire [31:0] b_i,',
             '    input  wire        signed_a_i,', '    input  wire        signed_b_i,',
             '    output wire [63:0] product_o', ');',
             '    wire signed_a = signed_a_i;', '    wire signed_b = signed_b_i;',
             '    wire [1023:0] pp;', '    wire [2175:0] initial_heap;',
             '    genvar a_bit, b_bit;', '    generate',
             '        for (a_bit = 0; a_bit < 32; a_bit = a_bit + 1) begin : gen_a',
             '            for (b_bit = 0; b_bit < 32; b_bit = b_bit + 1) begin : gen_b',
             '                assign pp[32*a_bit+b_bit] = (a_i[a_bit] & b_i[b_bit]) ^',
             '                    (((a_bit == 31) && signed_a) ^ ((b_bit == 31) && signed_b));',
             '            end', '        end', '    endgenerate']
    lines += packed_assignments('initial_heap', initial_columns(32), 34)
    previous = 'initial_heap'
    for stage in stages:
        height = stage.target
        lines += [f'    wire [{64*height-1}:0] heap_h{height};',
                  f'    uqu_daddamul_reduce_{height} u_reduce_h{height} (',
                  f'        .heap_i({previous}), .heap_o(heap_h{height})', '    );']
        previous = f'heap_h{height}'
    lines += ['    // Carry outputs are already packed at their actual weights.',
              '    assign product_o = heap_h2[63:0] + heap_h2[127:64];', 'endmodule', '']
    for stage in stages:
        height = stage.target
        full = sum(len(c.inputs) == 3 for c in stage.counters)
        half = len(stage.counters)-full
        lines += [f'// Reduce height {max(stage.input_heights)} to {height}: {full} FAs, {half} HAs,',
                  f'// {sum(stage.output_heights)} live output dots. Output carries are already aligned.',
                  f'module uqu_daddamul_reduce_{height} (',
                  f'    input  wire [{64*max(stage.input_heights)-1}:0] heap_i,',
                  f'    output wire [{64*height-1}:0] heap_o', ');']
        for name, count in (('fa', full), ('ha', half)):
            if count:
                lines += [f'    wire [{count-1}:0] {name}_sum;', f'    wire [{count-1}:0] {name}_carry;']
        for c in stage.counters:
            a, b, *third = c.inputs
            lines.append(f'    assign {c.sum} = '+' ^ '.join(c.inputs)+';')
            carry = f'({a} & {b})'
            if third:
                z = third[0]
                carry += f' | ({a} & {z}) | ({b} & {z})'
            lines.append(f'    assign {c.carry} = {carry};')
        lines += packed_assignments('heap_o', stage.output_columns, height)
        lines += ['endmodule', '']
    lines += ['`default_nettype wire', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--output', type=Path, default=OUTPUT)
    args = parser.parse_args()
    result = generate()
    if args.check:
        if not args.output.is_file() or args.output.read_text() != result:
            raise SystemExit('Generated Dadda RTL is stale; run scripts/gen_daddamul.py')
        print('Generated Dadda RTL matches the generator.')
    else:
        args.output.write_text(result)
        print(args.output)


if __name__ == '__main__':
    main()
